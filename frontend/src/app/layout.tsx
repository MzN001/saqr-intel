import type { Metadata, Viewport } from "next";
import { Barlow, Gloock, IBM_Plex_Sans_Arabic, Inter, Noto_Kufi_Arabic } from "next/font/google";
import { ThemeScript } from "@/components/ThemeScript";
import "./globals.css";

// Self-hosted at build time (no request to Google from the visitor).
// Saqr: Inter (UI) -> --font-sans, IBM Plex Sans Arabic -> --font-arabic, Gloock (wordmark only) -> --font-wordmark.
const inter = Inter({ subsets: ["latin"], variable: "--font-inter", display: "swap" });
const plexArabic = IBM_Plex_Sans_Arabic({
  subsets: ["arabic"],
  weight: ["400", "500", "600", "700"],
  variable: "--font-plex-arabic",
  display: "swap",
});
const gloock = Gloock({ subsets: ["latin"], weight: "400", variable: "--font-gloock", display: "swap" });
// Legacy Night Grid fonts, used only inside the `.brand-night-grid` scope (/police). Not preloaded,
// so citizen pages never download them.
const barlow = Barlow({
  subsets: ["latin"],
  weight: ["300", "400", "500", "600", "700", "800"],
  variable: "--font-barlow",
  display: "swap",
  preload: false,
});
const kufi = Noto_Kufi_Arabic({ subsets: ["arabic"], variable: "--font-kufi", display: "swap", preload: false });

export const metadata: Metadata = {
  title: "Saqr — Abu Dhabi Anti-Scam Shield",
  description: "Check any link, message, email or Maps listing before you trust it. Free scam protection for Abu Dhabi residents, no app install required.",
  applicationName: "Saqr",
  appleWebApp: { capable: true, title: "Saqr", statusBarStyle: "default" },
  // Tab icons come from the file conventions: app/icon.svg, app/favicon.ico, app/apple-icon.png
  // (all generated by scripts/brand/generate-icons.mjs).
};

export const viewport: Viewport = {
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#F7F5F0" },
    { media: "(prefers-color-scheme: dark)", color: "#0E1012" },
  ],
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
};

export default function RootLayout({ children }: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      lang="en"
      dir="ltr"
      suppressHydrationWarning
      className={`${inter.variable} ${plexArabic.variable} ${gloock.variable} ${barlow.variable} ${kufi.variable}`}
    >
      <head>
        <ThemeScript />
      </head>
      <body className="min-h-dvh antialiased">{children}</body>
    </html>
  );
}
